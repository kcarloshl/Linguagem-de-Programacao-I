    private void jbCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbCalcularActionPerformed
        // TODO add your handling code here:

        double peso;
        double altura;
        double IMC;

        if (jtfAltura.getText().trim().equals("") || jtfPeso.getText().trim().equals("")) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
            return;
        }

        try {
            altura = Double.parseDouble(jtfAltura.getText().replace(",", "."));
            peso = Double.parseDouble(jtfPeso.getText().replace(",", "."));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Digite apenas números!");
            return;
        }

        if (peso <= 0 || altura <= 0) {
            JOptionPane.showMessageDialog(this, "Digite valores positivos para peso e altura!");
            return;
        }

        IMC = peso / (altura * altura);

        ButtonModel sel = bgGenero.getSelection();
        if (sel != null) {
            String op = sel.getActionCommand();
            if (op == "1") {
                if (IMC < 20.7) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Abaixo do Peso.");
                } else if (IMC >= 20.7 && IMC < 26.4) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Peso Normal.");
                } else if (IMC >= 26.4 && IMC < 27.8) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Sobrepeso.");
                } else if (IMC >= 27.8 && IMC < 31.1) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Obesidade Leve.");
                } else if (IMC >= 31.1) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Obesidade.");
                }
            } else {
                if (IMC < 19.1) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Abaixo do Peso.");
                } else if (IMC >= 19.1 && IMC < 25.8) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Peso Normal.");
                } else if (IMC >= 25.8 && IMC < 27.3) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Sobrepeso.");
                } else if (IMC >= 27.3 && IMC < 32.3) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Obesidade Leve.");
                } else if (IMC >= 32.3) {
                    JOptionPane.showMessageDialog(this, "Seu IMC é " + IMC + ": Obesidade.");
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Por favor escolha um gênero!");
        }
    }//GEN-LAST:event_jbCalcularActionPerformed

