    private void jbCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbCalcularActionPerformed
        // TODO add your handling code here:
        
        String texto = jtfRS.getText().trim();
        
        if(texto.equals("")) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
            return;
        }
        
        double real;
        try {
            real = Double.parseDouble(texto.replace(",", "."));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Digite apenas números.");
            return;
        }
        
        if(real <= 0) {
            JOptionPane.showMessageDialog(this, "Digite valores maiores que zero!");
            return;
        }
        
        String a = jcbMoeda.getSelectedItem().toString();
        
        if(a.equals("Dólar (USD)")) {
            real = real / 5.6;
            JOptionPane.showMessageDialog(this, "US$" + real);
        } else if(a.equals("Euro (EUR)")) {
            real = real / 6.1;
            JOptionPane.showMessageDialog(this, "€" + real);
        } else if(a.equals("Libra (GBP)")) {
            real = real / 7;
            JOptionPane.showMessageDialog(this, "£" + real);
        } else if(a.equals("Peso Argentino (ARS)")) {
            real = real / 0.03;
            JOptionPane.showMessageDialog(this, "$" + real);
        }
    }//GEN-LAST:event_jbCalcularActionPerformed

